use std::process::Command;

fn svg(args: &[&str]) -> String {
    let out = Command::new(env!("CARGO_BIN_EXE_pixban"))
        .args(args)
        .output()
        .unwrap();
    assert!(
        out.status.success(),
        "pixban {args:?} failed: {}",
        String::from_utf8_lossy(&out.stderr)
    );
    String::from_utf8(out.stdout).unwrap()
}

macro_rules! preset {
    ($name:ident, $($arg:expr),+ $(,)?) => {
        #[test]
        fn $name() {
            insta::assert_snapshot!(svg(&[$($arg),+]));
        }
    };
}

